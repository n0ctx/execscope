def counts(text):
    return [len(tiktoken.get_encoding(name).encode(text)) for name in ENCODINGS]


def to_rust(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{code:x}}}")
    return '"' + "".join(out) + '"'


def write():
    rows = [f"    ({to_rust(t)}, {o}, {c})," for t in CORPUS for o, c in [counts(t)]]
    FIXTURE.parent.mkdir(exist_ok=True)
    FIXTURE.write_text(
        f"// Generated by tests/token_calibration.py with tiktoken {tiktoken.__version__}: (text, o200k_base, cl100k_base)\n"
        "&[\n" + "\n".join(rows) + "\n]\n", encoding="utf-8")
    print(f"wrote {len(rows)} rows to {FIXTURE}")


def check(binary, cwd):
    for scope in ("auto", "harness", "all"):
        for budget in (100, 600, 3000):
            args = [str(binary), "inspect", "--scope", scope, "--brief-tokens", str(budget), "--requires", "git,node,cargo"]
            if cwd:
                args += ["--cwd", str(cwd)]
            text = subprocess.run(args, capture_output=True, text=True, encoding="utf-8", check=True, timeout=10).stdout.removesuffix("\n")
            text.encode("utf-8").decode("utf-8")
            reference = max(counts(text))
            assert reference <= budget, (scope, budget, reference, text)
            print(f"scope={scope} budget={budget} reference_tokens={reference} chars={len(text)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("binary", nargs="?", type=Path)
    parser.add_argument("--cwd", type=Path)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        write()
    if args.binary:
        check(args.binary.resolve(), args.cwd)


if __name__ == "__main__":
    main()
